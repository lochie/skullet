import { build } from "esbuild";
import { readFileSync, writeFileSync } from "fs";
import { dirname, resolve } from "path";
import { fileURLToPath } from "url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const target = resolve(root, "src/lib/inline.generated.ts");

/** boot.ts bundled into one minified script, as a string the wrappers render inline. */
export async function inlineScript() {
  const { outputFiles } = await build({
    entryPoints: [resolve(root, "src/lib/boot.ts")],
    bundle: true,
    minify: true,
    format: "iife",
    target: "es2020",
    write: false,
  });
  // `</script` inside would end the element early
  return outputFiles[0].text.trim().replaceAll("</", "<\\/");
}

// Calls the boot a full script earlier in the page left on window, or queues for one still to come
const STUB = `(s=>{let k=Symbol.for("skullet.boot"),b=self[k];typeof b=="function"?b(s):(self[k]=b||[]).push(s)})(document.currentScript)`;

export const source = (script) =>
  `// Generated by scripts/build-inline.mjs from boot.ts — don't edit\nexport const INLINE_SCRIPT = ${JSON.stringify(script)};\n\n/** For every skeleton after a page's first: calls the boot INLINE_SCRIPT left on window. */\nexport const INLINE_STUB = ${JSON.stringify(STUB)};\n\n/** Either, as a whole element — for templates where a literal script tag would be read as the component's own. */\nexport const inlineScriptTag = (nonce?: string, stub = false) =>\n  \`<script\${nonce ? \` nonce="\${nonce.replace(/"/g, "&quot;")}"\` : ""}>\${stub ? INLINE_STUB : INLINE_SCRIPT}</script>\`;\n`;

/** What's committed, for the test that it's current. */
export function committed() {
  try {
    return readFileSync(target, "utf8");
  } catch {
    return "";
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = source(await inlineScript());
  if (next !== committed()) writeFileSync(target, next);
}
